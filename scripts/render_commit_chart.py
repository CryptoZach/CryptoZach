    per_unit = PX_PER_1000 * 4000.0 / top / 1000.0
    xs = [X0 + i * step for i in range(n)]
    ys = [Y0 - v * per_unit for v in counts_3d]
    pts = " ".join(f"{x:.1f},{y:.1f}" for x, y in zip(xs, ys))
