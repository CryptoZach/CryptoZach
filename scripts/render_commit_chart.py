#!/usr/bin/env python3
"""render_commit_chart.py: build and stamp the interactive fleet commit chart on /agent-infrastructure/.

Sources of truth:
1. When `/Users/zach/Tokenization_Systems_Website` (or `--workflow-repo`) is available and
   `--refresh` is passed (or when `agent-infrastructure/commits-per-3-days.json` does not yet
   carry `series_1d`), reads committer timestamps from `origin/main` in the workflow repository
   and computes:
   - `series` (`series_3d`): 3-day bin counts starting 2026-03-02 in America/New_York time
     through the last complete 3-day bin.
   - `series_1d`: daily commit counts starting 2026-03-02 in America/New_York time through
     the end of the last complete 3-day bin.
2. Otherwise reads `agent-infrastructure/commits-per-3-days.json` directly so `--check` and
   `--write` work in CI where only the public site repository is checked out.

Outputs updated by `--write`:
- `agent-infrastructure/commits-per-3-days.json`
- `agent-infrastructure/commits-per-3-days.svg`
- `agent-infrastructure/commits-per-3-days.png` (when `--png` or `--refresh` is passed and Chrome is available)
- `agent-infrastructure/index.html` (interactive chart markup + inline SVG + embedded JSON + meta alt text)
- `README.md` (profile chart date range)
- `sitemap.xml` (image title date range)
"""
