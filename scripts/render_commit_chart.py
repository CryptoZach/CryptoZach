ZONE = ZoneInfo("America/New_York")
START = dt.date(2026, 3, 2)
BIN_DAYS = 3
X0, X1, Y0 = 78.0, 928.0, 352.0
PX_PER_1000 = 66.5
FONT = "JetBrains Mono, ui-monospace, Menlo, monospace"
MONTHS = [
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
]

FIG_START = "<!-- commit-chart:figure START (generated by scripts/render_commit_chart.py --write) -->"
FIG_END = "<!-- commit-chart:figure END -->"


def committer_times(wf_repo: Path, ref: str = "origin/main"):
    git_bin = "/Library/Developer/CommandLineTools/usr/bin/git"
    if not os.path.exists(git_bin):
        git_bin = "git"
    r = subprocess.run(
        [git_bin, "--no-optional-locks", "-C", str(wf_repo), "log", ref, "--format=%ct"],
        capture_output=True, text=True,
    )
    if r.returncode != 0 or not r.stdout.strip():
        raise RuntimeError(f"git log {ref} failed in {wf_repo}: {r.stderr.strip()[:200]}")
    return [int(x) for x in r.stdout.split()]


def last_complete_bin(now: dt.datetime) -> int:
    return (now.astimezone(ZONE).date() - START).days // BIN_DAYS - 1


def bin_days(i: int):
    a = START + dt.timedelta(days=BIN_DAYS * i)
    return a, a + dt.timedelta(days=BIN_DAYS - 1)


def compute_series(times, last_bin: int):
    counts_3d = [0] * (last_bin + 1)
    n_days = (last_bin + 1) * BIN_DAYS
    counts_1d = [0] * n_days
    for ts in times:
        k = (dt.datetime.fromtimestamp(ts, ZONE).date() - START).days
        if k < 0:
            continue
        if k < n_days:
            counts_1d[k] += 1
        i = k // BIN_DAYS
        if i <= last_bin:
            counts_3d[i] += 1
    return counts_3d, counts_1d


def captions(counts_3d):
    last = len(counts_3d) - 1
    end = bin_days(last)[1]
    peak_i = max(range(len(counts_3d)), key=lambda i: (counts_3d[i], -i))
    a, b = bin_days(peak_i)
    through = f"{end.day} {MONTHS[end.month - 1]} {end.year}"
    peak = f"Peak {counts_3d[peak_i]:,} from {a.day} {MONTHS[a.month - 1]} to {b.day} {MONTHS[b.month - 1]}."
    span = f"March through {through}"
    short = (
        f"{MONTHS[a.month - 1][:3]} {a.day}-{b.day}"
        if a.month == b.month
        else f"{MONTHS[a.month - 1][:3]} {a.day}-{MONTHS[b.month - 1][:3]} {b.day}"
    ).upper()
    return {
        "through": through,
        "peak_value": counts_3d[peak_i],
        "peak_index": peak_i,
        "peak_short": short,
        "svg_aria": f"Commits per 3 days, {span}. {peak}",
        "svg_footer": span.upper(),
        "page_img_alt": f"Commits per three days, {span}. Fleet workload. {peak}",
        "social_alt": f"Fleet commits per three days, {span}. {peak}",
        "readme_line": f"Commits per three days, {span}. The series is fleet workload. {peak}",
        "sitemap_title": f"Fleet commits per three days, {span}",
    }


def month_ticks(n_bins: int):
    out, end = [("Mar", 0)], bin_days(n_bins - 1)[1]
    y, m = START.year, START.month + 1
    while dt.date(y, m, 1) <= end:
        pos = math.ceil((dt.date(y, m, 1) - START).days / BIN_DAYS)
        if pos <= n_bins - 1:
            out.append((MONTHS[m - 1][:3], pos))
        y, m = (y + 1, 1) if m == 12 else (y, m + 1)
    return out


