def render_png(svg_text: str, out_png: Path, font_path: Path):
    js = f"""
    const fs = require("fs");
    const {{ chromium }} = require("playwright");
    (async () => {{
      const b64 = fs.readFileSync({json.dumps(str(font_path))}).toString("base64");
      const face = `@font-face{{font-family:'JetBrains Mono';src:url(data:font/woff2;base64,${{b64}}) format('woff2');font-weight:100 800}}`;
      const svgBody = {json.dumps(svg_text.split("?>", 1)[-1])};
      const html = `<!doctype html><meta charset=utf-8><style>${{face}} html,body{{margin:0;background:transparent}}svg{{display:block}}</style>${{svgBody}}`;
      const browser = await chromium.launch({{ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true }});
      const page = await browser.newPage({{ viewport: {{ width: 960, height: 440 }}, deviceScaleFactor: 2 }});
      await page.setContent(html, {{ waitUntil: "load" }});
      await page.evaluate(() => document.fonts.ready);
      await page.waitForTimeout(300);
      await page.screenshot({{ path: {json.dumps(str(out_png))}, omitBackground: true, clip: {{ x: 0, y: 0, width: 960, height: 440 }} }});
      await browser.close();
    }})();
    """
    env = dict(os.environ, NODE_PATH="/Users/zach/ai-research/CryptoZach/node_modules")
    subprocess.run(["node", "-e", js], cwd=str(ROOT), env=env, check=True)


def load_or_refresh_data(wf_repo: Path, ref: str, force_refresh: bool):
    if (force_refresh or not JSON_PATH.is_file()) and wf_repo.is_dir():
        times = committer_times(wf_repo, ref)
        now = dt.datetime.now(dt.timezone.utc)
        last = last_complete_bin(now)
        counts_3d, counts_1d = compute_series(times, last)
        cap = captions(counts_3d)
        return {
            "measured_at": now.strftime("%Y-%m-%dT%H:%M:%SZ"),
            "ref": ref,
            "commits_on_ref": len(times),
            "start_date": START.isoformat(),
            "bin_days": BIN_DAYS,
            "definition": "committer time, America/New_York calendar day, three-day bins from 2026-03-02",
            "bins": len(counts_3d),
            "commits_in_series": sum(counts_3d),
            "series": counts_3d,
            "series_1d": counts_1d,
            "captions": cap,
        }, True
    if not JSON_PATH.is_file():
        raise RuntimeError(f"{JSON_PATH} not found and workflow repo {wf_repo} unavailable")
    doc = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    if "series_1d" not in doc and wf_repo.is_dir():
        return load_or_refresh_data(wf_repo, ref, True)
    return doc, False


def sync_page_html(page_text: str, doc: dict) -> str:
    cap = doc["captions"]
    fig_block = build_figure_block(doc)
    if FIG_START in page_text and FIG_END in page_text:
        s = page_text.index(FIG_START)
        e = page_text.index(FIG_END) + len(FIG_END)
        page_text = page_text[:s] + fig_block + page_text[e:]
    else:
        old_fig_re = re.compile(
            r'[ \t]*<figure class="ai-commit-chart">.*?</figure>',
            re.S,
        )
        m = old_fig_re.search(page_text)
        if not m:
            raise RuntimeError("Could not find <figure class=\"ai-commit-chart\"> in agent-infrastructure/index.html")
        page_text = page_text[:m.start()] + fig_block + page_text[m.end():]

    page_text = re.sub(
        r'(<meta property="og:image:alt" content=")Fleet commits per three days, [^"]+(")',
        r"\g<1>" + cap["social_alt"] + r"\g<2>",
        page_text,
    )
    page_text = re.sub(
        r'(<meta name="twitter:image:alt" content=")Fleet commits per three days, [^"]+(")',
        r"\g<1>" + cap["social_alt"] + r"\g<2>",
        page_text,
    )
    return page_text


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="Check that SVG, JSON, and HTML match (default)")
    ap.add_argument("--quiet", action="store_true", help="Suppress OK output")
    ap.add_argument("--write", action="store_true", help="Write updated JSON, SVG, and HTML in place")
    ap.add_argument("--refresh", action="store_true", help="Refresh commit series from workflow repo origin/main")
    ap.add_argument("--png", action="store_true", help="Also re-render commits-per-3-days.png via headless Chrome")
    ap.add_argument("--workflow-repo", default=str(DEFAULT_WF_REPO))
    ap.add_argument("--ref", default="origin/main")
    args = ap.parse_args(argv)

    try:
        doc, refreshed = load_or_refresh_data(Path(args.workflow_repo), args.ref, args.refresh)
    except Exception as exc:
        print(f"render_commit_chart: WARN could not load commit series ({exc})", file=sys.stderr)
        return 2

    expected_svg = build_svg(doc["series"], interactive_ids=False)
    expected_json = json.dumps(doc, indent=2) + "\n"
    page_orig = PAGE_PATH.read_text(encoding="utf-8")
    expected_page = sync_page_html(page_orig, doc)

    cap = doc["captions"]
    readme_orig = README_PATH.read_text(encoding="utf-8") if README_PATH.is_file() else ""
    through_iso = bin_days(doc["bins"] - 1)[1].isoformat()
    expected_readme = re.sub(
        r"Commits per three days, March through [^\n]+\.",
        cap["readme_line"],
        readme_orig,
    )
    expected_readme = re.sub(
        r"(?:\[!\[Fleet commits per three days, [^\]]+\]\(agent-infrastructure/commits-per-3-days\.png(?:\?v=[^)]+)?\)\]\(https://tokenization\.systems/agent-infrastructure/#ai-commit-chart\)|!\[Fleet commits per three days, [^\]]+\]\(agent-infrastructure/commits-per-3-days\.png(?:\?v=[^)]+)?\))",
        f"[![{cap['social_alt']}](agent-infrastructure/commits-per-3-days.png?v={through_iso})](https://tokenization.systems/agent-infrastructure/#ai-commit-chart)",
        expected_readme,
    )

    sitemap_orig = SITEMAP_PATH.read_text(encoding="utf-8") if SITEMAP_PATH.is_file() else ""
    expected_sitemap = re.sub(
        r"<image:title>Fleet commits per three days, [^<]+</image:title>",
        f"<image:title>{cap['sitemap_title']}</image:title>",
        sitemap_orig,
    )

    if args.write:
        if args.refresh and Path(args.workflow_repo).is_dir():
            wf = Path(args.workflow_repo)
            draft_script = wf / "scripts" / "draft_site_figures_revision.py"
            if draft_script.is_file():
                subprocess.run(
                    [sys.executable, str(draft_script), "--site", str(ROOT), "--apply", "--draft-agreeing"],
                    cwd=str(wf), check=False,
                )
        page_orig = PAGE_PATH.read_text(encoding="utf-8")
        expected_page = sync_page_html(page_orig, doc)
        JSON_PATH.write_text(expected_json, encoding="utf-8")
        SVG_PATH.write_text(expected_svg, encoding="utf-8")
        PAGE_PATH.write_text(expected_page, encoding="utf-8")
        if README_PATH.is_file() and expected_readme != readme_orig:
            README_PATH.write_text(expected_readme, encoding="utf-8")
        if SITEMAP_PATH.is_file() and expected_sitemap != sitemap_orig:
            SITEMAP_PATH.write_text(expected_sitemap, encoding="utf-8")
        if (args.png or refreshed) and FONT_PATH.is_file():
            try:
                render_png(expected_svg, PNG_PATH, FONT_PATH)
            except Exception as exc:
                print(f"render_commit_chart: WARN PNG render skipped ({exc})", file=sys.stderr)
        print(
            f"render_commit_chart: WROTE {doc['bins']} bins through {cap['through']} "
            f"({doc['commits_in_series']:,} commits in series, {doc['commits_on_ref']:,} on ref)."
        )
        return 0

    problems = []
    if not JSON_PATH.is_file():
        problems.append("agent-infrastructure/commits-per-3-days.json is missing")
    if not SVG_PATH.is_file() or SVG_PATH.read_text(encoding="utf-8") != expected_svg:
        problems.append("agent-infrastructure/commits-per-3-days.svg is out of sync with commits-per-3-days.json")
    if expected_page != page_orig:
        problems.append("agent-infrastructure/index.html commit-chart region is out of sync with commits-per-3-days.json")
    if README_PATH.is_file() and expected_readme != readme_orig:
        problems.append("README.md fleet commit chart caption/link is out of sync with commits-per-3-days.json")
    if SITEMAP_PATH.is_file() and expected_sitemap != sitemap_orig:
        problems.append("sitemap.xml fleet commit chart title is out of sync with commits-per-3-days.json")
    if problems:
        for p in problems:
            print(f"render_commit_chart: DRIFT: {p}")
        return 1

    if not args.quiet:
        print(
            f"render_commit_chart: OK ({doc['bins']} bins through {cap['through']}, "
            f"peak {cap['peak_value']:,})."
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
